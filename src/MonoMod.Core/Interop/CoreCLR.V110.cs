                // vm/genmeth.cpp:761 MethodDesc::FindOrCreateAssociatedMethodDesc
                //
                // Ported for the arguments GetAsyncVariantNoCreate and GetOrdinaryVariantNoCreate pass: pExactMT is
                // pDefMD->GetMethodTable() (so GetExactDeclaringType is the identity), forceBoxedEntryPoint = FALSE,
                // methodInst = pDefMD->GetMethodInstantiation(), allowInstParam = TRUE, forceRemotableMethod = FALSE, and
                // allowCreate = FALSE. The cases that look in the loader module's InstMethodHashTable (generic method
                // instantiations and instantiating stubs) are not ported and return null.
                private static MethodDesc* FindOrCreateAssociatedMethodDesc(MethodDesc* pDefMD, AsyncVariantLookup asyncVariantLookup)
                {
                    var pExactMT = pDefMD->GetMethodTable();
                    var methodInst = pDefMD->GetMethodInstantiation();

                    // Quick exit for the common cases where the result is the same as the primary MD we are given
                    if (!pDefMD->HasClassOrMethodInstantiation() &&
                        methodInst.IsEmpty() &&
                        // !forceBoxedEntryPoint &&
                        !pDefMD->IsUnboxingStub() &&
                        pDefMD->MatchesAsyncVariantLookup(asyncVariantLookup))
                    {
                        return pDefMD;
                    }

                    // Get the version of the method desc. for the instantiated shared class, e.g.
                    //  e.g. if pDefMD == List<T>.m()
                    //          pExactMT = List<string>
                    //     then pMDescInCanonMT = List<object>.m()
                    // or
                    //  e.g. if pDefMD == List<T>.m<U>()
                    //          pExactMT = List<string>
                    //     then pMDescInCanonMT = List<object>.m<U>()

                    var pMDescInCanonMT = pDefMD;

                    if (pDefMD->HasClassOrMethodInstantiation() ||
                        !methodInst.IsEmpty() ||
                        !pDefMD->MatchesAsyncVariantLookup(asyncVariantLookup))
                    {
                        // (The arity and instantiation checks always pass, methodInst being pDefMD's own instantiation.)

                        pMDescInCanonMT = pExactMT->GetCanonicalMethodTable()->GetParallelMethodDesc(pDefMD, asyncVariantLookup);
                        // (GetParallelMethodDesc can fail when there is no such variant, which the runtime never asks for.)
                        if (pMDescInCanonMT == null)
                        {
                            return null;
                        }

                        if (/* !allowCreate && */ !pMDescInCanonMT->GetMethodTable()->IsFullyLoaded())
                        {
                            return null;
                        }

                        // pMDescInCanonMT->CheckRestore(level);
                    }

                    // This case covers nearly all "normal" (i.e. non-associate) MethodDescs.  Just return
                    // the MethodDesc in the canonical method table.
                    //
                    // Also, it will be taken for methods which acquire their type context from the "this" parameter
                    // - we don't need instantiating stubs for these.
                    if (methodInst.IsEmpty()
                        // && (allowInstParam || !pMDescInCanonMT->RequiresInstArg())
                        && (/* forceBoxedEntryPoint */ false == pMDescInCanonMT->IsUnboxingStub())
                        // && (!forceRemotableMethod || ...)
                        && (pMDescInCanonMT->MatchesAsyncVariantLookup(asyncVariantLookup)))
                    {
                        return pMDescInCanonMT;
                    }

                    // (Unboxing stubs: only for forceBoxedEntryPoint.)

                    // Now all generic method instantiations and static/shared-struct-instance-method wrappers...

                    // (ClassLoader::IsTypicalInstantiation(pModule, methodDef, methodInst) is TRUE for an empty
                    // instantiation. Non-empty ones need TypeVarTypeDesc, and are then found in the InstMethodHashTable.)
                    if (!methodInst.IsEmpty())
                    {
                        return null;
                    }

                    // Some unboxed entry points are attached to canonical method tables.  This is because
                    // we have to fill in vtables and/or dispatch maps at load time,
                    // and boxed entry points are created to do this. (note vtables and dispatch maps
                    // are only created for canonical instantiations).  These boxed entry points
                    // in turn refer to unboxed entry points.

                    if (// Check if we're looking for something at the canonical instantiation
                        /* (allowInstParam || pExactMT->IsCanonicalMethodTable()) && */
                        // Only value types have BoxedEntryPointStubs in the canonical method table
                        pExactMT->IsValueType())
                    {
                        var pResultMD = FindTightlyBoundWrappedMethodDesc(pMDescInCanonMT);

                        if (pResultMD != null)
                        {
                            // if (allowInstParam || !pResultMD->RequiresInstArg())
                            return pResultMD;
                        }
                    }

                    // Are either the generic type arguments or the generic method arguments shared?
                    // (ClassLoader::IsSharableInstantiation is FALSE for an empty instantiation.)
                    var sharedInst = pExactMT->GetCanonicalMethodTable()->IsSharedByGenericInstantiations();

                    // Is it the "typical" instantiation in the correct type that does not require wrapper?
                    if (!sharedInst &&
                        pExactMT == pMDescInCanonMT->GetMethodTable())
                    {
                        Helpers.DAssert(!pMDescInCanonMT->IsUnboxingStub());
                        return pMDescInCanonMT;
                    }

                    // OK, so we now know the thing we're looking for can only be found in the MethodDesc table.
                    // (The InstMethodHashTable is not mirrored.)
                    return null;
                }

