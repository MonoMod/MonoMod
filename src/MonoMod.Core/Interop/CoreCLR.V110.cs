                // Methods added by EnC cannot be looked up by slot since
                // they have none, see EEClass::AddMethodDesc(). We must perform
                // a slow lookup instead of using the fast slot lookup path.
                private static MethodDesc* GetParallelMethodDescForEnC(MethodTable* pMT, MethodDesc* pDefMD)
                {
                    Helpers.DAssert(pMT != null);
                    Helpers.DAssert(pMT->IsCanonicalMethodTable());
                    Helpers.DAssert(pDefMD != null);
                    Helpers.DAssert(pDefMD->IsEnCAddedMethod());

                    var tkMethod = pDefMD->GetMemberDef();
                    var mod = pDefMD->GetModule();

                    var it = new IntroducedMethodIterator(pMT);
                    for (; it.IsValid(); it.Next())
                    {
                        var pMD = it.GetMethodDesc();
                        if (pMD->GetMemberDef() == tkMethod
                            && pMD->GetModule() == mod
                            && pMD->MatchesAsyncVariantLookup(pDefMD->GetMatchingAsyncVariantLookup()))
                        {
                            return pMD;
                        }
                    }
                    return null;
                }

