                    //
                    // Mapping the code in the slot back to its MethodDesc (decoding precodes, or the ExecutionManager)
                    // is not mirrored, so the search the runtime uses for empty slots is used in all cases. It finds
                    // the MethodDesc that owns the slot, which is the one whose code is in it unless a MethodImpl
                    // put another one there.

                    // This code path should only be hit for methods which have not been overridden
                    var pMTToSearchForMethodDesc = GetCanonicalMethodTable();
                    while (pMTToSearchForMethodDesc != null)
                    {
                        var it = new IntroducedMethodIterator(pMTToSearchForMethodDesc);
                        for (; it.IsValid(); it.Next())
                        {
                            if (it.GetMethodDesc()->GetSlot() == slot)
                            {
                                return it.GetMethodDesc();
                            }
                        }

                        pMTToSearchForMethodDesc = pMTToSearchForMethodDesc->GetParentMethodTable();
                        if (pMTToSearchForMethodDesc != null)
                        {
                            pMTToSearchForMethodDesc = pMTToSearchForMethodDesc->GetCanonicalMethodTable();
                        }
                    }
